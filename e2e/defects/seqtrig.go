package main

// Risk hunt R03 and R04 (block 7): what an application's framework reads of a LokaDB table's
// key sequence and what its trigger functions see of the table's name.

import (
	"fmt"
	"strings"
)

func init() {
	checks = append(checks,
		check{id: "M17", name: "pg_get_serial_sequence of a LokaDB table finds its sequence after enable, move-org, move-back and disable (serial and identity): Django's sequence reset after loading fixtures works", run: checkSerialSequence},
		check{id: "M18", name: "a row trigger of a LokaDB table sees the table's name, schema and OID, not the partition's, for a cloud and a moved organization, for a function made after enable through the proxy too; disable gives the functions their text back", run: checkTriggerNames},
	)
}

// M17. enable made the table DEFAULT of a new parent: the sequence stayed owned by the
// original table (an identity's by none), pg_get_serial_sequence('documents', 'id') was NULL,
// and the reset frameworks do after loading rows with explicit ids did nothing: the next
// ordinary insert collided with a loaded id.
func checkSerialSequence(e *env) (bool, string, error) {
	// document_versions.id an identity (Rails 7, Django 4.1+ BigAutoField on Postgres)
	if err := execSQL(e.ctx, e.cloud(),
		"ALTER TABLE document_versions ALTER COLUMN id DROP DEFAULT",
		"DROP SEQUENCE IF EXISTS document_versions_id_seq",
		"ALTER TABLE document_versions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100000)"); err != nil {
		return false, "", err
	}
	seq := func(t string) string {
		v, err := one(e.ctx, e.cloud(), fmt.Sprintf("SELECT coalesce(pg_get_serial_sequence('%s', 'id'), 'NULL')", t))
		if err != nil {
			return "error: " + firstErrLine(err)
		}
		return v
	}
	var notes []string
	ok := true
	note := func(good bool, s string) {
		if !good {
			ok = false
			s = "WRONG " + s
		}
		notes = append(notes, s)
	}
	before := seq("documents")
	// Django: loaddata writes explicit ids, then sqlsequencereset's statement; then an
	// ordinary insert (both as the application's role, in the cloud)
	djangoReset := func(stage string, id int) {
		val := func(q string) string {
			v, err := one(e.ctx, e.cloud(), q)
			if err != nil {
				return "error: " + firstErrLine(err)
			}
			return v
		}
		fixture := val(fmt.Sprintf("INSERT INTO documents (id, organization_id, user_id, title) VALUES (%d, 2, 3, 'fixture') RETURNING id", id))
		reset := val(`SELECT coalesce(setval(pg_get_serial_sequence('"documents"','id'), coalesce(max("id"), 1), max("id") IS NOT null)::text, 'NULL') FROM "documents"`)
		next := val("INSERT INTO documents (organization_id, user_id, title) VALUES (2, 3, 'next') RETURNING id")
		note(fixture == fmt.Sprint(id) && reset == fmt.Sprint(id) && next == fmt.Sprint(id+1),
			fmt.Sprintf("%s: fixture id %s, Django's reset gives %s, the next insert %s", stage, fixture, reset, next))
	}
	if err := e.enable(); err != nil {
		return false, "enable failed: " + firstErrLine(err), nil
	}
	enabled, enabledV := seq("documents"), seq("document_versions")
	note(enabled == before && enabledV != "NULL", fmt.Sprintf("after enable: documents %s (before %s), document_versions (identity) %s", enabled, before, enabledV))
	djangoReset("after enable", 500000)
	if out, err := e.move(1); err != nil {
		return false, strings.Join(notes, "; ") + "; move-org failed: " + lastErr(out), nil
	}
	note(seq("documents") == before && seq("document_versions") == enabledV, fmt.Sprintf("after move-org: %s, %s", seq("documents"), seq("document_versions")))
	djangoReset("after move-org", 600000)
	if _, err := e.run6(e.moveBackArgs(1)...); err != nil {
		return false, strings.Join(notes, "; ") + "; move-back failed: " + errLine(err), nil
	}
	if _, err := e.run6(e.disableArgs()...); err != nil {
		return false, strings.Join(notes, "; ") + "; disable failed: " + errLine(err), nil
	}
	ident, _ := one(e.ctx, e.cloud(), "SELECT attidentity::text FROM pg_attribute WHERE attrelid = 'document_versions'::regclass AND attname = 'id'")
	note(seq("documents") == before && seq("document_versions") != "NULL" && ident == "d",
		fmt.Sprintf("after disable: documents %s, document_versions %s (identity %q)", seq("documents"), seq("document_versions"), ident))
	djangoReset("after disable", 700000)
	return ok, strings.Join(notes, "; "), nil
}

// M18. A row trigger of a partitioned table fires on the partition: an audit trigger wrote
// "documents__cloud" and "documents__org1", not "documents" (pg_notify(TG_TABLE_NAME, …)
// listeners heard another channel).
func checkTriggerNames(e *env) (bool, string, error) {
	const fn = `CREATE FUNCTION %s() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- TG_TABLE_NAME in a comment and 'TG_TABLE_NAME' in a literal stay as they are
  INSERT INTO audit (fn, tbl, sch, rel, note) VALUES ('%s', TG_TABLE_NAME, TG_TABLE_SCHEMA, TG_RELID::regclass::text, 'TG_TABLE_NAME');
  RETURN NEW;
END $$`
	if err := execSQL(e.ctx, e.cloud(),
		"CREATE TABLE audit (id bigserial PRIMARY KEY, fn text, tbl text, sch text, rel text, note text)",
		"GRANT INSERT ON audit TO app", "GRANT USAGE ON SEQUENCE audit_id_seq TO app",
		fmt.Sprintf(fn, "audit_before", "before"),
		"CREATE TRIGGER audit_before AFTER INSERT ON documents FOR EACH ROW EXECUTE FUNCTION audit_before()"); err != nil {
		return false, "", err
	}
	if err := e.enable(); err != nil {
		return false, "enable failed: " + firstErrLine(err), nil
	}
	if out, err := e.move(1, "-customer-app", e.appCustomer()); err != nil {
		return false, "move-org failed: " + lastErr(out), nil
	}
	stop, err := e.proxy()
	if err != nil {
		return false, "", err
	}
	c, err := e.viaProxy()
	if err != nil {
		stop()
		return false, "", err
	}
	run := func(q string) error { _, err := simple(e.ctx, c, q); return err }
	var notes []string
	ok := true
	// a trigger function of a migration after enable, through the proxy
	errAfter := run(fmt.Sprintf(fn, "audit_after", "after"))
	if errAfter == nil {
		errAfter = run("CREATE TRIGGER audit_after AFTER INSERT ON documents FOR EACH ROW EXECUTE FUNCTION audit_after()")
	}
	if errAfter != nil {
		ok = false
		notes = append(notes, "the trigger of a migration after enable: "+errText(errAfter))
	}
	write := func(stage string, insert func(string) error) string {
		if err := execSQL(e.ctx, e.cloud(), "TRUNCATE audit"); err != nil {
			return "error: " + firstErrLine(err)
		}
		for _, o := range []int{1, 2} {
			if err := insert(fmt.Sprintf("INSERT INTO documents (organization_id, user_id, title) VALUES (%d, 2, '%s')", o, stage)); err != nil {
				return "error: " + firstErrLine(err)
			}
		}
		v, err := one(e.ctx, e.cloud(), "SELECT string_agg(DISTINCT tbl || '/' || sch || '/' || rel || '/' || note, ' ') FROM audit")
		if err != nil {
			return "error: " + firstErrLine(err)
		}
		n, _ := one(e.ctx, e.cloud(), "SELECT count(*) FROM audit")
		return v + " (" + n + " rows)"
	}
	moved := write("moved", run)
	c.Close(e.ctx)
	stop()
	want := "documents/public/documents/TG_TABLE_NAME"
	good := moved == want+" (4 rows)" || moved == want+" (2 rows)" && errAfter != nil
	if !good {
		ok = false
	}
	notes = append(notes, "organizations 1 (moved) and 2 (cloud), two triggers: "+moved)
	if _, err := e.run6(e.moveBackArgs(1)...); err != nil {
		return false, strings.Join(notes, "; ") + "; move-back failed: " + errLine(err), nil
	}
	if _, err := e.run6(e.disableArgs()...); err != nil {
		return false, strings.Join(notes, "; ") + "; disable failed: " + errLine(err), nil
	}
	src, _ := one(e.ctx, e.cloud(), "SELECT string_agg((prosrc LIKE '%lokadb.tg_%')::text || '/' || (prosrc LIKE '%VALUES%TG_TABLE_NAME, TG_TABLE_SCHEMA, TG_RELID%')::text, ' ' ORDER BY proname) FROM pg_proc WHERE proname IN ('audit_before', 'audit_after')")
	plain := write("plain", func(q string) error { return execSQL(e.ctx, e.cloud(), q) })
	notes = append(notes, fmt.Sprintf("after disable: the functions (rewritten/their own text) %s; inserts log %s", src, plain))
	ok = ok && src == "false/true false/true" && plain == want+" (4 rows)"
	return ok, strings.Join(notes, "; "), nil
}
