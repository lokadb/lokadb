\c postgres
CREATE DATABASE richapp OWNER app;
\c richapp
CREATE EXTENSION postgres_fdw;
CREATE EXTENSION citext;
CREATE EXTENSION pg_trgm;
CREATE TYPE doc_status AS ENUM ('draft', 'published');
CREATE DOMAIN posint AS int CHECK (VALUE > 0);
CREATE FUNCTION norm(text) RETURNS text LANGUAGE sql IMMUTABLE AS 'SELECT lower($1)';
CREATE TABLE documents (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id bigint NOT NULL,
  title text NOT NULL CHECK (title <> ''), slug citext, body text, name text COLLATE "en-x-icu",
  status doc_status NOT NULL DEFAULT 'draft', price posint,
  body_len int GENERATED ALWAYS AS (length(body)) STORED,
  words int GENERATED ALWAYS AS (array_length(string_to_array(body, ' '), 1)) VIRTUAL);
CREATE INDEX documents_body_trgm ON documents USING gin (body gin_trgm_ops);
CREATE INDEX documents_norm_title ON documents (norm(title));
CREATE TABLE notes (id bigint NOT NULL, organization_id bigint NOT NULL, txt text NOT NULL);
